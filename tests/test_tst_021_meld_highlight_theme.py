"""
@brief Validate the meld-highlight-theme pipeline end-to-end against
  byte-identical reference fixtures generated by
  `bin/Meld_Create_TextHighlight.sh`.
@details HDT Generator-mode suite.
  Static analysis artifact:
  UUTs: `shell_scripts.commands.meld_highlight_theme.build_xml` (Level 0:
  pure XML construction), `..._build_parser` (Level 0), `...all_schemes`
  (Level 1: filesystem scan), `...run` (Level N: discovery, generation,
  planning, backup, atomic write, reporting).
  External dependencies isolated: filesystem (fixture trees staged into
  `tmp_path` with monkeypatched `SOURCE_DIRS`/`TARGET_DIRS`), stdout
  (capsys), wall clock (backup names asserted by prefix only).
  Reference fixtures live under `tests/fixtures/meld_highlight/` and were
  produced by executing `bin/Meld_Create_TextHighlight.sh` with `--light`,
  `--dark`, and `--only-meld-base --dark` against the same staged source
  schemes.
@satisfies TST-021, REQ-156, REQ-157, REQ-158, REQ-159, REQ-160, REQ-161,
REQ-162, REQ-163, REQ-164, REQ-165, REQ-166, REQ-167, REQ-168
@return {None} Pytest module scope.
"""

import shutil
import xml.etree.ElementTree as ET
from pathlib import Path

import pytest

import shell_scripts.commands.meld_highlight_theme as meld_theme
from shell_scripts.commands import get_command

FIXTURE_ROOT = Path(__file__).parent / "fixtures" / "meld_highlight"
FIXTURE_HOME = FIXTURE_ROOT / "home"
STYLES_REL = Path(".local/share/meld/styles")
GENERATED_SCHEMES = ("meld-base", "meld-dark", "sample-dark", "sample-light")
EXCLUDED_SCHEMES = ("legacy-highlight", "texthighlight-old")


def _stage_fixture_home(tmp_path):
    """
    @brief Copy the fixture home tree into one isolated temporary directory.
    @details Returns the staged style directory containing the committed
      source schemes (meld-base, meld-dark, sample-dark, sample-light,
      excluded schemes, and one invalid XML file).
    @param tmp_path {Path} Pytest per-test temporary directory.
    @return {Path} Staged `<tmp>/home/.local/share/meld/styles` directory.
    """
    home = tmp_path / "home"
    shutil.copytree(FIXTURE_HOME, home)
    return home / STYLES_REL


def _patch_dirs(monkeypatch, styles_dir):
    """
    @brief Redirect module discovery and target directories to one fixture dir.
    @details Patches `meld_theme.SOURCE_DIRS` and `meld_theme.TARGET_DIRS` so
      the pipeline scans and writes only inside the staged fixture home.
    @param monkeypatch {pytest.MonkeyPatch} Runtime patch helper.
    @param styles_dir {Path} Staged style directory.
    @return {None} Patches only.
    """
    monkeypatch.setattr(meld_theme, "SOURCE_DIRS", [styles_dir])
    monkeypatch.setattr(meld_theme, "TARGET_DIRS", [styles_dir])


def _expected(name, variant):
    """
    @brief Load one committed reference fixture payload.
    @param name {str} Scheme id without the `-highlight` suffix.
    @param variant {str} Fixture variant directory (`expected_light`,
      `expected_dark`, `expected_only_meld_base_dark`).
    @return {bytes} Reference XML document bytes.
    """
    return (FIXTURE_ROOT / variant / f"{name}-highlight.xml").read_bytes()


def test_build_xml_light_payload_matches_reference_fixture():
    """
    @brief Validate the plain highlight payload against the bash reference.
    @details Builds the light payload for `meld-base` and asserts byte
      equality with `expected_light/meld-base-highlight.xml` generated by
      `bin/Meld_Create_TextHighlight.sh --light`.
    @return {None} Assertions only.
    @expected_output Byte-identical XML payload.
    @satisfies TST-021, REQ-159, REQ-160, REQ-165
    """
    source_root = ET.parse(
        FIXTURE_HOME / STYLES_REL / "meld-base.style-scheme.xml"
    ).getroot()

    payload = meld_theme.build_xml("meld-base", "Classic (Meld)")

    assert payload == _expected("meld-base", "expected_light")
    assert source_root.get("id") == "meld-base"


def test_build_xml_dark_payload_matches_reference_fixture():
    """
    @brief Validate the dark-palette payload against the bash reference.
    @details Builds the `meld-base` payload inheriting the fixture
      `meld-dark` palette and asserts byte equality with
      `expected_dark/meld-base-highlight.xml` generated by
      `bin/Meld_Create_TextHighlight.sh --dark`.
    @return {None} Assertions only.
    @expected_output Byte-identical XML payload with inherited Meld styles.
    @satisfies TST-021, REQ-159, REQ-161, REQ-162, REQ-165
    """
    dark_root = ET.parse(FIXTURE_HOME / STYLES_REL / "meld-dark.style-scheme.xml").getroot()

    payload = meld_theme.build_xml("meld-base", "Classic (Meld)", dark_root)

    assert payload == _expected("meld-base", "expected_dark")


def test_build_xml_missing_required_dark_style_raises_value_error():
    """
    @brief Validate the dark-palette completeness gate.
    @details Builds with a palette whose styles lack `meld:replace` and
      asserts `ValueError` naming the missing style.
    @expected_exception {ValueError} Mentioning `meld:replace`.
    @satisfies TST-021, REQ-162
    """
    palette = ET.Element("style-scheme", {"id": "meld-dark"})
    ET.SubElement(palette, "style", {"name": "meld:insert", "background": "#000000"})

    with pytest.raises(ValueError, match="meld:replace"):
        meld_theme.build_xml("meld-base", "Classic (Meld)", palette)


def test_all_schemes_discovers_and_parses_fixture_schemes(tmp_path, monkeypatch):
    """
    @brief Validate discovery, name resolution, and invalid-file skipping.
    @details Scans the staged fixture styles directory and asserts the exact
      discovered id set (including schemes later excluded from generation),
      the resolved display names, and that the invalid `junk.xml` file is
      silently skipped.
    @return {None} Assertions only.
    @satisfies TST-021, REQ-157
    """
    styles = _stage_fixture_home(tmp_path)
    _patch_dirs(monkeypatch, styles)
    schemes = meld_theme.all_schemes()

    assert set(schemes) == {"meld-base", "meld-dark", "sample-dark", "sample-light"} | set(EXCLUDED_SCHEMES)
    assert schemes["meld-base"][0] == "Classic (Meld)"
    assert schemes["sample-light"][0] == "Sample Light"
    assert schemes["legacy-highlight"][0] == "Legacy Highlight"


@pytest.mark.parametrize("variant,args", [
    ("expected_light", ["--light"]),
    ("expected_dark", ["--dark"]),
])
def test_run_generates_reference_fixtures_byte_identical(
    tmp_path, monkeypatch, capsys, variant, args
):
    """
    @brief Validate full-pipeline byte equality with the bash reference.
    @details Runs the command with the isolated fixture directories and
      asserts every generated scheme file equals the bash-generated
      reference payload and the excluded schemes produce no output.
    @param tmp_path {Path} Pytest per-test temporary directory.
    @param monkeypatch {pytest.MonkeyPatch} Runtime patch helper.
    @param capsys {pytest.CaptureFixture} Stdout capture fixture.
    @param variant {str} Reference variant directory name.
    @param args {list[str]} Command arguments selecting the palette.
    @return {None} Assertions only.
    @expected_output Byte-identical generated XML files.
    @satisfies TST-021, REQ-156, REQ-157, REQ-158, REQ-163, REQ-164, REQ-166
    """
    styles = _stage_fixture_home(tmp_path)
    _patch_dirs(monkeypatch, styles)

    result = meld_theme.run(args)

    assert result == 0
    for name in GENERATED_SCHEMES:
        generated = styles / f"{name}-highlight.xml"
        assert generated.is_file()
        assert generated.read_bytes() == _expected(name, variant)
    for name in EXCLUDED_SCHEMES:
        assert not (styles / f"{name}-highlight.xml").exists()
    assert f"Completed: {len(GENERATED_SCHEMES)} variants" in capsys.readouterr().out


def test_run_only_meld_base_writes_single_dark_scheme(tmp_path, monkeypatch):
    """
    @brief Validate `--only-meld-base` generation scope.
    @details Runs `--only-meld-base --dark` and asserts only
      `meld-base-highlight.xml` is written with the dark reference payload.
    @param tmp_path {Path} Pytest per-test temporary directory.
    @param monkeypatch {pytest.MonkeyPatch} Runtime patch helper.
    @return {None} Assertions only.
    @expected_output Single byte-identical `meld-base-highlight.xml`.
    @satisfies TST-021, REQ-156, REQ-161, REQ-166
    """
    styles = _stage_fixture_home(tmp_path)
    _patch_dirs(monkeypatch, styles)

    result = meld_theme.run(["--only-meld-base", "--dark"])

    assert result == 0
    inventory = sorted(path.name for path in styles.iterdir())
    assert inventory == sorted([
        "junk.xml",
        "legacy-highlight.xml",
        "meld-base.style-scheme.xml",
        "meld-dark.style-scheme.xml",
        "meld-base-highlight.xml",
        "sample-dark.xml",
        "sample-light.xml",
        "texthighlight-old.xml",
    ])
    assert (styles / "meld-base-highlight.xml").read_bytes() == _expected(
        "meld-base", "expected_only_meld_base_dark"
    )


def test_run_is_idempotent_on_unchanged_targets(tmp_path, monkeypatch, capsys):
    """
    @brief Validate byte-equality skip behavior on the second run.
    @details Runs the same palette twice and asserts the second run reports
      zero written files, zero backups, and creates no backup or temporary
      residue.
    @param tmp_path {Path} Pytest per-test temporary directory.
    @param monkeypatch {pytest.MonkeyPatch} Runtime patch helper.
    @param capsys {pytest.CaptureFixture} Stdout capture fixture.
    @return {None} Assertions only.
    @expected_output Second-run summary with `0 files written, 0 backups`.
    @satisfies TST-021, REQ-166, REQ-167, REQ-168
    """
    styles = _stage_fixture_home(tmp_path)
    _patch_dirs(monkeypatch, styles)

    assert meld_theme.run(["--light"]) == 0
    assert meld_theme.run(["--light"]) == 0

    output = capsys.readouterr().out
    assert "0 files written, 0 backups" in output
    assert not list(styles.glob("*.bak-*"))
    assert not list(styles.glob("*.tmp-*"))


def test_run_replaces_stale_file_with_timestamped_backup(tmp_path, monkeypatch):
    """
    @brief Validate stale-file replacement and backup creation.
    @details Pre-writes a stale `meld-base-highlight.xml`, runs the light
      palette, and asserts the file content equals the light reference and a
      single `.bak-<timestamp>` backup preserves the stale bytes.
    @param tmp_path {Path} Pytest per-test temporary directory.
    @param monkeypatch {pytest.MonkeyPatch} Runtime patch helper.
    @return {None} Assertions only.
    @expected_output Replaced payload plus one backup with stale content.
    @satisfies TST-021, REQ-166, REQ-167
    """
    stale_payload = b"<stale>legacy-content</stale>\n"
    styles = _stage_fixture_home(tmp_path)
    _patch_dirs(monkeypatch, styles)
    (styles / "meld-base-highlight.xml").write_bytes(stale_payload)

    assert meld_theme.run(["--light"]) == 0

    assert (styles / "meld-base-highlight.xml").read_bytes() == _expected(
        "meld-base", "expected_light"
    )
    backups = list(styles.glob("meld-base-highlight.xml.bak-*"))
    assert len(backups) == 1
    assert backups[0].read_bytes() == stale_payload


def test_run_rejects_combined_dark_and_light_flags(tmp_path, monkeypatch, capsys):
    """
    @brief Validate the mutually exclusive palette selector gate.
    @details Runs with both `--dark` and `--light` and asserts `SystemExit`
      with code `2` and a usage diagnostic on stderr, without writing files.
    @param tmp_path {Path} Pytest per-test temporary directory.
    @param monkeypatch {pytest.MonkeyPatch} Runtime patch helper.
    @param capsys {pytest.CaptureFixture} Stdout/stderr capture fixture.
    @return {None} Assertions only.
    @expected_exception {SystemExit} Exit code `2`.
    @satisfies TST-021, REQ-156
    """
    styles = _stage_fixture_home(tmp_path)
    _patch_dirs(monkeypatch, styles)

    with pytest.raises(SystemExit) as excinfo:
        meld_theme.run(["--dark", "--light"])

    assert excinfo.value.code == 2
    assert sorted(path.name for path in styles.iterdir()) == sorted([
        "junk.xml",
        "legacy-highlight.xml",
        "meld-base.style-scheme.xml",
        "meld-dark.style-scheme.xml",
        "sample-dark.xml",
        "sample-light.xml",
        "texthighlight-old.xml",
    ])


def test_run_only_meld_base_requires_meld_base_scheme(tmp_path, monkeypatch, capsys):
    """
    @brief Validate the `--only-meld-base` precondition gate.
    @details Points discovery at an empty directory, runs
      `--only-meld-base --light`, and asserts `SystemExit` code `2` naming
      the missing scheme.
    @param tmp_path {Path} Pytest per-test temporary directory.
    @param monkeypatch {pytest.MonkeyPatch} Runtime patch helper.
    @param capsys {pytest.CaptureFixture} Stdout/stderr capture fixture.
    @return {None} Assertions only.
    @expected_exception {SystemExit} Exit code `2`.
    @satisfies TST-021, REQ-164
    """
    empty = tmp_path / "empty-styles"
    empty.mkdir()
    _patch_dirs(monkeypatch, empty)

    with pytest.raises(SystemExit) as excinfo:
        meld_theme.run(["--only-meld-base", "--light"])

    assert excinfo.value.code == 2
    assert "meld-base" in capsys.readouterr().err


def test_run_dark_requires_meld_dark_scheme(tmp_path, monkeypatch, capsys):
    """
    @brief Validate the dark-palette `meld-dark` precondition gate.
    @details Stages a directory containing only `meld-base`, runs `--dark`,
      and asserts `SystemExit` code `2` naming the missing `meld-dark`
      scheme.
    @param tmp_path {Path} Pytest per-test temporary directory.
    @param monkeypatch {pytest.MonkeyPatch} Runtime patch helper.
    @param capsys {pytest.CaptureFixture} Stdout/stderr capture fixture.
    @return {None} Assertions only.
    @expected_exception {SystemExit} Exit code `2`.
    @satisfies TST-021, REQ-164
    """
    styles = _stage_fixture_home(tmp_path)
    for path in styles.iterdir():
        if path.name not in ("meld-base.style-scheme.xml",):
            path.unlink()
    _patch_dirs(monkeypatch, styles)

    with pytest.raises(SystemExit) as excinfo:
        meld_theme.run(["--dark"])

    assert excinfo.value.code == 2
    assert "meld-dark" in capsys.readouterr().err


